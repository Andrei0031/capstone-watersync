$error_message = '';

// Handle form actions
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action'])) {
    $admin_id = $_SESSION['admin_id'];
    $selected_billing_cycle_id = isset($_POST['billing_cycle_id']) && $_POST['billing_cycle_id'] !== '' 
        ? intval($_POST['billing_cycle_id']) 
        : null;
    
    switch ($_POST['action']) {
        case 'auto_generate':
            try {
                $generated_count = autoGenerateDisconnectionNotices($admin_id, $selected_billing_cycle_id);
                $success_message = "Successfully generated {$generated_count} disconnection notices.";
            } catch (Exception $e) {
                $error_message = "Error generating notices: " . $e->getMessage();
            }
            break;
            
        case 'send_notice':
            $notice_id = intval($_POST['notice_id']);
            $stmt = $conn->prepare("UPDATE disconnection_notices SET status = 'sent', sent_at = NOW() WHERE id = ?");
            $stmt->bind_param("i", $notice_id);
            if ($stmt->execute()) {
                $success_message = "Notice sent successfully.";
            } else {
                $error_message = "Error sending notice.";
            }
            break;
            
        case 'resolve_notice':
            $notice_id = intval($_POST['notice_id']);
            $resolution_notes = trim($_POST['resolution_notes']);
            $stmt = $conn->prepare("UPDATE disconnection_notices SET status = 'resolved', resolved_at = NOW(), resolution_notes = ? WHERE id = ?");
            $stmt->bind_param("si", $resolution_notes, $notice_id);
            if ($stmt->execute()) {
                $success_message = "Notice marked as resolved.";
            } else {
                $error_message = "Error resolving notice.";
            }
            break;
            
        case 'create_manual':
            $client_id = intval($_POST['client_id']);
            $notice_type = $_POST['notice_type'];
            $amount_due = floatval($_POST['amount_due']);
            $overdue_days = intval($_POST['overdue_days']);
            $due_date = $_POST['due_date'];
            $custom_description = trim($_POST['custom_description']);
            
            // Create manual notice
            $notice_data = [
                'type' => $notice_type,
                'bill' => ['id' => null, 'due_date' => $due_date],
                'total_amount' => $amount_due,
                'overdue_days' => $overdue_days,
                'reason' => 'Manual notice created by admin'
            ];
            
            if (!empty($custom_description)) {
                $notice_content = ['title' => 'Water Service Notice', 'description' => $custom_description];
                // Override generated content with custom description
            }
            
            if (createDisconnectionNotice($client_id, $notice_data, $admin_id)) {
                $success_message = "Manual disconnection notice created successfully.";
            } else {
                $error_message = "Error creating manual notice.";
            }
            break;
    }
}

// Get filter parameters
$status_filter = isset($_GET['status']) ? $_GET['status'] : '';
$type_filter = isset($_GET['type']) ? $_GET['type'] : '';
$billing_cycle_filter = isset($_GET['billing_cycle_id']) ? intval($_GET['billing_cycle_id']) : 0;
$search = isset($_GET['search']) ? $conn->real_escape_string($_GET['search']) : '';

// Build WHERE clause for filters
$where_conditions = [];
$params = [];
$types = '';

if ($search) {
    $where_conditions[] = "(cl.firstname LIKE ? OR cl.lastname LIKE ? OR cl.code LIKE ?)";
    $search_param = "%$search%";
    $params[] = $search_param;
    $params[] = $search_param;
    $params[] = $search_param;
    $types .= 'sss';
}

if ($status_filter) {
    $where_conditions[] = "dn.status = ?";
    $params[] = $status_filter;
    $types .= 's';
}

if ($type_filter) {
    $where_conditions[] = "dn.notice_type = ?";
    $params[] = $type_filter;
    $types .= 's';
}

if ($billing_cycle_filter) {
    $where_conditions[] = "bl.billing_cycle_id = ?";
    $params[] = $billing_cycle_filter;
    $types .= 'i';
}

$where_clause = $where_conditions ? 'WHERE ' . implode(' AND ', $where_conditions) : '';

// Get disconnection notices with client and billing cycle information
$sql = "SELECT dn.*, 
               cl.firstname, cl.lastname, cl.contact, cl.address, cl.code as client_code,
               a.username as created_by_username,
               bl.billing_cycle_id,
               bc.cycle_name
        FROM disconnection_notices dn
        JOIN client_list cl ON dn.client_id = cl.id
        JOIN admin a ON dn.created_by = a.id
        LEFT JOIN billing_list bl ON dn.billing_id = bl.id
        LEFT JOIN billing_cycles bc ON bl.billing_cycle_id = bc.id
        {$where_clause}
        ORDER BY dn.created_at DESC";

if ($types) {
    $stmt = $conn->prepare($sql);
    $stmt->bind_param($types, ...$params);
    $stmt->execute();
    $notices = $stmt->get_result();
} else {
    $notices = $conn->query($sql);
}

