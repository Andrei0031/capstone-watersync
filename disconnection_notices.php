document.addEventListener('DOMContentLoaded', function() {
    const themeToggle = document.getElementById('theme-toggle');
    const html = document.documentElement;
    
    const savedTheme = localStorage.getItem('theme') || 'light';
    html.setAttribute('data-theme', savedTheme);
    themeToggle.checked = savedTheme === 'dark';

    themeToggle.addEventListener('change', function() {
        const theme = this.checked ? 'dark' : 'light';
        html.setAttribute('data-theme', theme);
        localStorage.setItem('theme', theme);
    });

    // Auto-submit filter form when Status or Notice Type dropdowns change
    const statusSelect = document.getElementById('status');
    const typeSelect = document.getElementById('type');
    const filterForm = statusSelect ? statusSelect.closest('form') : null;

    if (statusSelect && filterForm) {
        statusSelect.addEventListener('change', function() {
            filterForm.submit();
        });
    }

    if (typeSelect && filterForm) {
        typeSelect.addEventListener('change', function() {
            filterForm.submit();
        });
    }
});

// Sidebar toggle for mobile
document.addEventListener('DOMContentLoaded', function() {
    var sidebar = document.getElementById('sidebar');
    var sidebarToggle = document.getElementById('sidebarToggle');
    if (sidebarToggle) {
        sidebarToggle.addEventListener('click', function() {
            sidebar.classList.toggle('open');
        });
    }
    document.addEventListener('click', function(e) {
        if (window.innerWidth <= 991 && sidebar.classList.contains('open')) {
            if (!sidebar.contains(e.target) && e.target !== sidebarToggle) {
                sidebar.classList.remove('open');
            }
        }
    });
});

function viewNotice(noticeId) {
    // Load notice details via AJAX
    fetch(`get_disconnection_notice.php?id=${noticeId}`)
        .then(response => response.json())
        .then(data => {
            if (data.success) {
                const notice = data.notice;
                document.getElementById('noticeDetailsContent').innerHTML = `
                    <div class="row">
                        <div class="col-md-6">
                            <h6>Client Information</h6>
                            <p><strong>Name:</strong> ${notice.client_name}</p>
                            <p><strong>Contact:</strong> ${notice.contact}</p>
                            <p><strong>Address:</strong> ${notice.address}</p>
                        </div>
                        <div class="col-md-6">
                            <h6>Notice Details</h6>
                            <p><strong>Type:</strong> ${notice.notice_type}</p>
                            <p><strong>Amount Due:</strong> ₱${parseFloat(notice.amount_due).toLocaleString()}</p>
                            <p><strong>Overdue Days:</strong> ${notice.overdue_days}</p>
                            <p><strong>Status:</strong> ${notice.status}</p>
                        </div>
                    </div>
                    <hr>
                    <h6>Notice Content</h6>
                    <h5>${notice.title}</h5>
                    <div style="white-space: pre-line;">${notice.description}</div>
                `;
                new bootstrap.Modal(document.getElementById('viewNoticeModal')).show();
            }
        })
        .catch(error => console.error('Error:', error));
}

function resolveNotice(noticeId) {
